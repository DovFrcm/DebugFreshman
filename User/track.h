/*
 * track.h - 4 路灰度循迹传感器 + 循迹控制器
 *
 * ==================================================================
 * 硬件
 * ==================================================================
 * 传感器阵列接在 PB12 / PB13 / PB14 / PB15 上（上拉输入），
 * 从左到右依次是 S1 S2 S3 S4 —— 也就是主板上丝印的 OUT1..OUT4：
 *
 *     车头方向
 *     S1     S2   S3     S4
 *   (最左)  (左中)(右中) (最右)
 *   PB12   PB13 PB14   PB15
 *
 * 传感器的输出是"看见黑线拉低"，所以读到 0 就是黑线。
 * 如果实测发现黑白反了（把车放在白纸上四个都显示黑），
 * 把下面 TRACK_BLACK_IS_LOW 改成 0 即可，不用动接线。
 *
 * ==================================================================
 * 控制思路（简单判断，不用 PD）
 * ==================================================================
 * 正常循迹只看"线偏到哪一侧去了"，不看偏多少。
 * 7 路阵列从车头看从左往右是 S1..S7，**正中间是 S4**：
 *
 *     中线左边压得比右边多                  -> 线在车的左边 -> 右轮加快
 *     中线右边压得比左边多                  -> 线在车的右边 -> 左轮加快
 *     左右一样多（含只有 S4）               -> 直行，两轮都跑基础速度
 *
 * 加速时至少要持续 TRACK_TURN_MS 这么久。
 *
 * ⚠ 判据是"**数中线左右各压了几路、再比大小**"，不是"左边有没有压、右边有没有压"。
 *   实车直线上一般两路同时压线，而且常常正好跨在中线两侧（S3+S4 / S4+S5）。
 *   写成"两侧都有压 = 对称 = 直行"的话，这两种最普通的图形会被判成正中，
 *   车就**一点都不修**。详见 track.c 里 MaskLean() 的注释。
 *
 * ⚠ 正中间那一路（S4）**不算进任何一边** —— 它是"在不在正中"的标志，
 *   不是"偏哪边"的证据。
 *
 * ==================================================================
 * 直角路口 / 折线
 * ==================================================================
 * **一侧整排全黑、而正中间是空的** 时，说明"前面已经没线了，线拐到一边去了"，
 * 直接进 SHARP 状态原地朝那一侧 90° 强转，转到正中间重新看到线为止：
 *
 *     0x07 = S1+S2+S3 全黑，S4 空  ->  线拐到左边 -> 原地左转 90°
 *     0x70 = S5+S6+S7 全黑，S4 空  ->  线拐到右边 -> 原地右转 90°
 *
 * 两个要点：
 *   1. **必须"整排"全黑**。只压一两路是直线上的漂移，温和修正就够了，
 *      原地 90° 转会过头。判据见 track.c 的 Sharp_EntryDir()。
 *   2. **正中间必须是空的**。正中间也黑（0x0F / 0x78）说明主线还在前面，
 *      那是 T 字路口 / 圆环入口，由 TRACK_RING_PAT_* 那套管。
 *
 * 方向约定：线偏左 -> 右轮快 -> 车头往左摆（追着线走）。
 *
 * "至少持续 TRACK_TURN_MS"这一步很关键：判出偏了就把这次修正锁定一段时间，
 * 期间即使传感器已经回到中间也继续修完 —— 不然会"一修就过头、一过头又反向修"
 * 地高频抖动。偏得久就每拍续期（一直修），回到中间后最多再修一期就收手。
 *
 * 另外仍然会算一个加权偏差 error（范围 -300..+300），但它**不参与控制**，
 * 只给状态机当判据（丢线时判断"刚才车正不正"，用来区分直线缺口和直角急弯），
 * 以及串口 STATUS 显示。
 *
 * 内轮不反转：倒转交给 SHARP 状态（原地强转），所以这里只封上限。
 *
 * ==================================================================
 * 特殊元素
 * ==================================================================
 * 十字  —— 全部压线（7 路全黑）时不再听转向判断的，直接"锁定直行"一小段时间，
 *          否则车会在路口被某个传感器的读数带偏。这同时也是起跑线的判据。
 * 直角/折线 —— 只剩最外侧一路压线时进入"强转"状态：朝线消失的那一侧原地转，
 *          直到中间几路重新压到线。
 * 断路  —— 丢线后先直行冲一段（TRACK_GAP_MS），冲不过去再原地找线。
 *          顺序不能反：一丢线就原地转的话，直线上的小断口会让车原地打转。
 * 圆环  —— 见 track.c 里 Ring 那一段，默认开启，可用菜单/串口关掉。
 *
 * ==================================================================
 * 调参
 * ==================================================================
 * 所有可调参数都集中在 track.c 顶部，并且大多能在 OLED 菜单里现场改
 * （巡线页面按 KEY_2 调速度），不用重新编译烧录。
 */

#ifndef __TRACK_H
#define __TRACK_H

#include <stdint.h>
#include <board.h>

/* ------------------------------------------------------------------ */
/* 传感器接线                                                          */
/* ------------------------------------------------------------------ */

/* 传感器阵列的**路数**在这里切换：
     4 = 四路灰度（PB12~PB15）
     7 = 七路灰度（PB12~PB15 + PA6 / PA7 / PB0）    ← 当前用的

   两种接法共用同一套代码，只靠这个宏切换：掩码位数、权重表、图形判据、
   屏幕上的方框个数、串口 S= 的位数全都跟着它走。

   想切回四路：把这里改成 4 重新编译就行 —— 硬件不用动，因为 PB12~PB15
   那四根线在两种接法里位置完全一样。
   引脚表见下面的 g_trackSensorPins[]，以后改接线只改那一张表。

   外面用 -DTRACK_SENSOR_COUNT=n 也能覆盖（宿主端测试就是靠这个，
   同一份源码分别按 4 路和 7 路各编译一遍测试）。 */
#ifndef TRACK_SENSOR_COUNT
#define TRACK_SENSOR_COUNT  7
#endif

/* 传感器引脚表：顺序 = 车头方向从左到右 S1..SN，定义在 track.c 顶部。
   之所以导出，是因为宿主端测试的"假硬件"也要用它把"第 i 路压线"翻译成
   对应引脚的电平 —— 只有共用同一张表，电脑上测出来的行为才和板子上一致。 */
typedef struct {
    GPIO_TypeDef *port;
    uint8_t       pin;
} SensorPin;

extern const SensorPin g_trackSensorPins[TRACK_SENSOR_COUNT];

/* 传感器"看见黑线"时输出什么电平 —— 按实际测到的填：
     1 = 看见黑线输出**低**电平（配内部上拉，很多灰度/红外模块是这种）
     0 = 看见黑线输出**高**电平

   屏幕上"黑白反了"（白底显示实心、压黑线显示空心）就把它反过来。
   **最终裁决标准是跑起来的方向**：直线修正方向 + 转弯方向必须都对。

   ⚠ 实测记录（2026-10，七路灰度模块）：
   - 填 0 时：直线修正方向反、转弯方向也反 —— 不能用；
   - 填 1 时：方向正确。
   - 所以以"方向对不对"为准。白底方框的观察在高度/阈值没调好时会误导
     （离地太高时白底也会读成"黑"）。 */
#define TRACK_BLACK_IS_LOW  1

/* 传感器装反了（S1 跑到最右边）就改成 1，不用重新焊 */
#define TRACK_REVERSE       0

/* ------------------------------------------------------------------ */
/* 运行状态                                                            */
/* ------------------------------------------------------------------ */

typedef enum {
    TRACK_ST_IDLE = 0,      /* 没发车，电机停着，只显示传感器          */
    TRACK_ST_RUN,           /* 正常循迹（简单转向）                    */
    TRACK_ST_CROSS,         /* 压在十字/起跑线上，锁定直行通过         */
    TRACK_ST_SHARP,         /* 强转中（直角 / 折线 / 圆环入口）        */
    TRACK_ST_GAP,           /* 丢线冲刺中（多半是断路）                */
    TRACK_ST_LOST,          /* 原地找线                                */
    TRACK_ST_RING,          /* 绕圆环中                                */
    TRACK_ST_FINISH         /* 跑完设定圈数，停车                      */
} TrackState;

/* ------------------------------------------------------------------ */
/* 接口                                                                */
/* ------------------------------------------------------------------ */

/* 配置 PB12..PB15 为上拉输入。请在 Board_Init() 之后调用。 */
void        Track_Init(void);

/* 读一次传感器：bit0=S1 .. bit3=S4，对应位为 1 表示该路压到黑线 */
uint8_t     Track_Read(void);

/* 消抖之后的传感器值。控制用的是它，OLED 显示的也是它 */
uint8_t     Track_ReadStable(void);

/* 最近一次算出来的偏差，范围 -300..+300 */
int16_t     Track_Error(void);

TrackState  Track_State(void);

/* 状态的中文名，给 OLED 用（返回的是码点数组） */
const uint16_t *Track_StateText(void);

/* 状态名的纯英文短标签，给串口日志用 */
const char *Track_StateTag(void);

/* 传感器值的 ASCII 位串，例如 "0110"（bit3 在左）。给串口用 */
const char *Track_BitsText(void);

uint8_t     Track_IsRunning(void);

/* 发车：蜂鸣器响一声、计时清零、圈数清零、状态进入 RUN。
   已经在跑就什么都不做。 */
void        Track_Start(void);

/* 停车：电机自由停止、状态回 IDLE。随时可调用（幂等） */
void        Track_Stop(void);

/* ---- 可在菜单里现场调整的参数 ---- */

/* 跑完设定圈数后要不要自动停车。默认开。
   关掉的话跑完就继续跑，不会停 —— 单独测某个元素时有用。 */
void        Track_SetFinishStop(uint8_t on);
uint8_t     Track_GetFinishStop(void);

void        Track_SetLaps(uint8_t laps);        /* 1 或 2，默认 1 */
uint8_t     Track_GetLaps(void);

/* 圈数在 1 和 2 之间来回切，供巡线页 / 巡线设置页的按键调用 */
void        Track_CycleLaps(void);

void        Track_SetBaseSpeed(uint16_t s);     /* 原始 PWM 值，默认 1800 */
uint16_t    Track_GetBaseSpeed(void);

/* 在预设的四个速度档之间往上切一档（到头绕回最慢）。
   巡线页的 K3 和巡线设置页的速度项都调它，两边行为保证一致。 */
void        Track_CycleSpeed(void);

void        Track_SetRingEnable(uint8_t on);    /* 圆环识别，默认开 */
uint8_t     Track_GetRingEnable(void);

void        Track_SetLineMark(uint8_t on);      /* 起跑线(四路全黑)计圈，默认开 */
uint8_t     Track_GetLineMark(void);

/* ---- 计时 ---- */

uint32_t    Track_ElapsedMs(void);  /* 从发车到现在的毫秒数，停车后保持不变 */
uint32_t    Track_LastLapMs(void);  /* 上一圈用时 */
uint8_t     Track_LapIndex(void);   /* 当前正在跑第几圈，从 1 开始 */
uint8_t     Track_LapsDone(void);   /* 已经跑完几圈 */

/* ---- 主循环 ---- */

/* 循迹控制器。主循环每轮调用一次，内部自己按 TRACK_CTRL_MS 限频。
   不在运行状态时只更新传感器显示，不动电机。 */
void        Track_Tick(void);

#endif /* __TRACK_H */
