/*
 * track.h - 4 路灰度循迹传感器 + 循迹控制器
 *
 * ==================================================================
 * 硬件
 * ==================================================================
 * 传感器阵列接在 PB12 / PB13 / PB14 / PB15 上（上拉输入），
 * 从左到右依次是 S1 S2 S3 S4 —— 也就是主板上丝印的 OUT1..OUT4：
 *
 *     车头方向
 *     S1     S2   S3     S4
 *   (最左)  (左中)(右中) (最右)
 *   PB12   PB13 PB14   PB15
 *
 * 传感器的输出是"看见黑线拉低"，所以读到 0 就是黑线。
 * 如果实测发现黑白反了（把车放在白纸上四个都显示黑），
 * 把下面 TRACK_BLACK_IS_LOW 改成 0 即可，不用动接线。
 *
 * ==================================================================
 * 控制思路
 * ==================================================================
 * 不采用"查表 + 一堆 if-else"的离散做法，而是把四个传感器的位置加权求
 * 偏差，再用 PD 控制器算出左右轮的速度差：
 *
 *     error = Σ(位置权重 × 该路是否压线) / 压线的路数     范围 -300..+300
 *     turn  = (Kp × error + Kd × Δerror) / 1000
 *     左轮  = 基础速度 + turn
 *     右轮  = 基础速度 - turn
 *
 * error > 0 表示线在车的右边，要给右转（左轮快、右轮慢）。
 *
 * 加权平均的好处是误差是**连续**的：S3 压线是 +100、S4 压线是 +300、
 * S3+S4 一起压线是 +200。离散查表在这三种情况之间是跳变的，车会一顿一顿；
 * 连续误差就能让车平滑地贴着线走，过弯时也不会冲出赛道。
 *
 * 内轮允许反转（最多 -TRACK_REV_LIMIT），这样急弯时能原地转，
 * 直角和折线才过得去。
 *
 * ==================================================================
 * 特殊元素
 * ==================================================================
 * 十字  —— 四路全黑时不再听 PD 的，直接"锁定直行"一小段时间，
 *          否则车会在路口被某个传感器的读数带偏。这同时也是起跑线的判据。
 * 直角/折线 —— 偏差很大时自动进入"强转"状态：朝线消失的那一侧原地转，
 *          直到中间两路重新压到线。
 * 断路  —— 丢线后先直行冲一段（TRACK_GAP_MS），冲不过去再原地找线。
 *          顺序不能反：一丢线就原地转的话，直线上的小断口会让车原地打转。
 * 圆环  —— 见 track.c 里 Ring 那一段，默认开启，可用菜单/串口关掉。
 *
 * ==================================================================
 * 调参
 * ==================================================================
 * 所有可调参数都集中在 track.c 顶部，并且大多能在 OLED 菜单里现场改
 * （巡线页面按 KEY_2 调速度），不用重新编译烧录。
 */

#ifndef __TRACK_H
#define __TRACK_H

#include <stdint.h>
#include <board.h>

/* ------------------------------------------------------------------ */
/* 传感器接线                                                          */
/* ------------------------------------------------------------------ */

#define TRACK_PORT          GPIOB
#define TRACK_PIN_S1        12u     /* 最左   */
#define TRACK_PIN_S2        13u     /* 左中   */
#define TRACK_PIN_S3        14u     /* 右中   */
#define TRACK_PIN_S4        15u     /* 最右   */

/* 传感器"看见黑线"输出低电平。实测反了就改成 0 */
#define TRACK_BLACK_IS_LOW  0

/* 传感器装反了（S1 跑到最右边）就改成 1，不用重新焊 */
#define TRACK_REVERSE       0

/* ------------------------------------------------------------------ */
/* 运行状态                                                            */
/* ------------------------------------------------------------------ */

typedef enum {
    TRACK_ST_IDLE = 0,      /* 没发车，电机停着，只显示传感器          */
    TRACK_ST_RUN,           /* 正常循迹（PD 控制）                     */
    TRACK_ST_CROSS,         /* 压在十字/起跑线上，锁定直行通过         */
    TRACK_ST_SHARP,         /* 强转中（直角 / 折线 / 圆环入口）        */
    TRACK_ST_GAP,           /* 丢线冲刺中（多半是断路）                */
    TRACK_ST_LOST,          /* 原地找线                                */
    TRACK_ST_RING,          /* 绕圆环中                                */
    TRACK_ST_FINISH         /* 跑完设定圈数，停车                      */
} TrackState;

/* ------------------------------------------------------------------ */
/* 接口                                                                */
/* ------------------------------------------------------------------ */

/* 配置 PB12..PB15 为上拉输入。请在 Board_Init() 之后调用。 */
void        Track_Init(void);

/* 读一次传感器：bit0=S1 .. bit3=S4，对应位为 1 表示该路压到黑线 */
uint8_t     Track_Read(void);

/* 消抖之后的传感器值。控制用的是它，OLED 显示的也是它 */
uint8_t     Track_ReadStable(void);

/* 最近一次算出来的偏差，范围 -300..+300 */
int16_t     Track_Error(void);

TrackState  Track_State(void);

/* 状态的中文名，给 OLED 用（返回的是码点数组） */
const uint16_t *Track_StateText(void);

/* 状态名的纯英文短标签，给串口日志用 */
const char *Track_StateTag(void);

/* 传感器值的 ASCII 位串，例如 "0110"（bit3 在左）。给串口用 */
const char *Track_BitsText(void);

uint8_t     Track_IsRunning(void);

/* 发车：蜂鸣器响一声、计时清零、圈数清零、状态进入 RUN。
   已经在跑就什么都不做。 */
void        Track_Start(void);

/* 停车：电机自由停止、状态回 IDLE。随时可调用（幂等） */
void        Track_Stop(void);

/* ---- 可在菜单里现场调整的参数 ---- */

/* 跑完设定圈数后要不要自动停车。默认开。
   关掉的话跑完就继续跑，不会停 —— 单独测某个元素时有用。 */
void        Track_SetFinishStop(uint8_t on);
uint8_t     Track_GetFinishStop(void);

void        Track_SetLaps(uint8_t laps);        /* 1 或 2，默认 1 */
uint8_t     Track_GetLaps(void);

/* 圈数在 1 和 2 之间来回切，供巡线页 / 巡线设置页的按键调用 */
void        Track_CycleLaps(void);

void        Track_SetBaseSpeed(uint16_t s);     /* 原始 PWM 值，默认 1800 */
uint16_t    Track_GetBaseSpeed(void);

/* 在预设的四个速度档之间往上切一档（到头绕回最慢）。
   巡线页的 K3 和巡线设置页的速度项都调它，两边行为保证一致。 */
void        Track_CycleSpeed(void);

void        Track_SetRingEnable(uint8_t on);    /* 圆环识别，默认开 */
uint8_t     Track_GetRingEnable(void);

void        Track_SetLineMark(uint8_t on);      /* 起跑线(四路全黑)计圈，默认开 */
uint8_t     Track_GetLineMark(void);

/* ---- 计时 ---- */

uint32_t    Track_ElapsedMs(void);  /* 从发车到现在的毫秒数，停车后保持不变 */
uint32_t    Track_LastLapMs(void);  /* 上一圈用时 */
uint8_t     Track_LapIndex(void);   /* 当前正在跑第几圈，从 1 开始 */
uint8_t     Track_LapsDone(void);   /* 已经跑完几圈 */

/* ---- 主循环 ---- */

/* 循迹控制器。主循环每轮调用一次，内部自己按 TRACK_CTRL_MS 限频。
   不在运行状态时只更新传感器显示，不动电机。 */
void        Track_Tick(void);

#endif /* __TRACK_H */
