/*
 * motor.h - TB6612FNG 双路电机驱动（小车主板）
 *
 * 硬件接线（来自主板原理图和《单片机GPIO分配-蓝牙款》）：
 *
 *   通道 A（主板上标 PWMA/AIN1/AIN2，接右电机）
 *     AIN1 = PA4      AIN2 = PA5      PWMA = PB8  (TIM4_CH3)
 *   通道 B（主板上标 PWMB/BIN1/BIN2，接左电机）
 *     BIN1 = PA8      BIN2 = PA11     PWMB = PB9  (TIM4_CH4)
 *
 * TB6612 每个通道的真值表：
 *     IN1  IN2   电机
 *      0    0    自由停止（惯性滑行，最常用的"停"）
 *      1    0    正转
 *      0    1    反转
 *      1    1    刹车（把电机绕组短起来，急停）
 *
 * PWM 用 TIM4 的两个通道产生，10 kHz、7200 级分辨率：
 *     f = 72 MHz / (PSC+1) / (ARR+1) = 72e6 / 1 / 7200 = 10 kHz
 * 之所以选 7200 这么大的 ARR，是为了让低速段也有足够的分辨率 ——
 * ARR 只有几百的话，低速时"再慢一档"就没档可调了。
 *
 * 速度的表示方式：本模块统一用**有符号原始 PWM 值**，范围
 * -MOTOR_PWM_MAX .. +MOTOR_PWM_MAX，正数前进、负数后退、0 滑行。
 * 具体占空比 = |值| / 7200。
 *
 * ⚠ 调车第一步先验证转向
 *   把车架起来（轮子悬空），调用 Motor_SetLR(1500, 1500)，
 *   两个轮子都应该朝前转。如果某个轮子反了，有两条路：
 *     (a) 把那个电机的两根线对调（硬件，推荐，改完一劳永逸）；
 *     (b) 把下面 MOTOR_A_INVERT / MOTOR_B_INVERT 改成 1（软件）。
 *   如果"前进"时车往后走，说明整个 A/B 的左右映射反了，
 *   改 MOTOR_A_IS_LEFT 即可。
 */

#ifndef __MOTOR_H
#define __MOTOR_H

#include <stdint.h>
#include <board.h>

/* ------------------------------------------------------------------ */
/* 接线 / 方向修正（换车、换线序时只改这一段）                          */
/* ------------------------------------------------------------------ */

/* 主板上 A 通道接的是右电机（原理图丝印 AIN=A、备注"右电机"）。
   如果你的车装反了，把这里改成 1 */
#define MOTOR_A_IS_LEFT     0

/* 单个电机转向反了就置 1，不用拆线 */
#define MOTOR_A_INVERT      0
#define MOTOR_B_INVERT      0

/* ------------------------------------------------------------------ */
/* 接口                                                                */
/* ------------------------------------------------------------------ */

/* 配置方向引脚和 TIM4 的 PWM，并把占空比清零。
   请在 Board_Init() 之后调用（GPIO 时钟在那里才打开）。 */
void    Motor_Init(void);

/* 直接给左右两个轮子设有符号速度，内部会按 MOTOR_A_IS_LEFT 映射到 A/B 通道。
   范围 -MOTOR_PWM_MAX .. +MOTOR_PWM_MAX，超出去会被钳位。
   这是巡线控制器唯一需要调用的接口。 */
void    Motor_SetLR(int16_t left, int16_t right);

/* 自由停止：方向脚全 0、占空比清零，车会靠惯性滑行一小段。
   松手/退出巡线页用这个。 */
void    Motor_Stop(void);

/* 刹车急停：两个方向脚同时拉高，电机的反电动势被短路，
   停得比自由停止快得多。检测到危险时用。 */
void    Motor_Brake(void);

/* 上一轮实际写下去的左右速度，供 OLED 显示用（显示的是钳位之后的值，
   所以屏幕上看到的和真正给到电机的一定一致） */
int16_t Motor_GetLeft(void);
int16_t Motor_GetRight(void);

#endif /* __MOTOR_H */
